export const JOURNEY_MESSAGES: Readonly<
  Record<JourneyLocale, JourneyMessages>
> = {
  "zh-CN": zhCN,
  en,
  ja,
  ko,
};

export type JourneyMessageKey = keyof typeof en;

export function journeyMessage(
  locale: JourneyLocale,
  key: JourneyMessageKey,
  values: Readonly<Record<string, string | number>> = {},
) {
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    JOURNEY_MESSAGES[locale][key] as string,
  );
}
