import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import {
  mkdir,
  mkdtemp,
  readFile,
  readdir,
  rm,
  writeFile,
} from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PROJECT_IDS = new Set(["equal-love", "nearly-equal-joy", "not-equal-me"]);
const PRECACHE_STATIC_EXTENSIONS = new Set([".css", ".js"]);
const CACHE_VERSION_LENGTH = 16;
const COVER_CACHE_HEADROOM = 20;
const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);

export function renderDisabledServiceWorker() {
  return `// Generated by scripts/generate-service-worker.mjs --disable.
// This worker is the emergency rollback path. It intentionally handles no fetches.
const CACHE_PREFIX = "mypick-";

async function disableOfflineMode() {
  const cacheNames = await caches.keys();
  await Promise.all([
    self.registration.unregister(),
    ...cacheNames
      .filter((cacheName) => cacheName.startsWith(CACHE_PREFIX))
      .map((cacheName) => caches.delete(cacheName)),
  ]);
}

self.addEventListener("install", (event) => {
  event.waitUntil(disableOfflineMode());
});

self.addEventListener("activate", (event) => {
  event.waitUntil(disableOfflineMode());
});
`;
}

export async function generateServiceWorker({
  outputDirectory,
  projectId,
  songCount,
}) {
  assertProjectId(projectId);
  const entries = await collectPrecacheEntries(outputDirectory);
  const cacheVersion = computeCacheVersion(entries);
  const source = renderServiceWorker({
    cacheVersion,
    coverCacheLimit: songCount + COVER_CACHE_HEADROOM,
    entries,
    projectId,
  });
  await writeFile(path.join(outputDirectory, "sw.js"), source, "utf8");
  return { cacheVersion, entries, source };
}

export async function verifyGeneratedServiceWorker({
  outputDirectory,
  projectId,
  songCount,
}) {
  assertProjectId(projectId);
  const entries = await collectPrecacheEntries(outputDirectory);
  const cacheVersion = computeCacheVersion(entries);
  const expected = renderServiceWorker({
    cacheVersion,
    coverCacheLimit: songCount + COVER_CACHE_HEADROOM,
    entries,
    projectId,
  });
  const serviceWorkerPath = path.join(outputDirectory, "sw.js");
  let actual;
  try {
    actual = await readFile(serviceWorkerPath, "utf8");
  } catch (error) {
    throw new Error(
      `Missing service worker ${serviceWorkerPath}: ${error.message}`,
    );
  }
  if (actual !== expected) {
    throw new Error(
      "sw.js is stale or does not match the current project export; regenerate it after copying public assets",
    );
  }
  assertRuntimeWorkerContracts(actual, projectId);
  return { cacheVersion, entries };
}

export function computeCacheVersion(entries) {
  const digestInput = entries
    .map(({ sha256, url }) => `${url}\0${sha256}`)
    .sort()
    .join("\n");
  return createHash("sha256")
    .update(digestInput)
    .digest("hex")
    .slice(0, CACHE_VERSION_LENGTH);
}

function renderServiceWorker({
  cacheVersion,
  coverCacheLimit,
  entries,
  projectId,
}) {
  return `// Generated by scripts/generate-service-worker.mjs. Do not edit.
const PROJECT_ID = ${JSON.stringify(projectId)};
const PRECACHE_ENTRIES = Object.freeze(${JSON.stringify(entries, null, 2)});
const CACHE_VERSION = ${JSON.stringify(cacheVersion)};
const CACHE_PREFIX = "mypick-" + PROJECT_ID + "-";
const APP_CACHE_NAME = CACHE_PREFIX + CACHE_VERSION;
const COVER_CACHE_NAME = APP_CACHE_NAME + "-covers";
const ACTIVE_CACHE_NAMES = new Set([APP_CACHE_NAME, COVER_CACHE_NAME]);
const COVER_PATH_PREFIX = ${JSON.stringify(`/covers/${projectId}/`)};
const COVER_CACHE_LIMIT = ${coverCacheLimit};
const PRECACHE_URLS = new Set(PRECACHE_ENTRIES.map((entry) => entry.url));

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(APP_CACHE_NAME)
      .then((cache) => cache.addAll(Array.from(PRECACHE_URLS))),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const cacheNames = await caches.keys();
      await Promise.all(
        cacheNames
          .filter(
            (cacheName) =>
              cacheName.startsWith(CACHE_PREFIX) &&
              !ACTIVE_CACHE_NAMES.has(cacheName),
          )
          .map((cacheName) => caches.delete(cacheName)),
      );
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (url.pathname.startsWith(COVER_PATH_PREFIX)) {
    event.respondWith(serveProjectCover(request));
    return;
  }

  // Covers belonging to another project remain network-only.
  if (url.pathname.startsWith("/covers/")) return;

  if (PRECACHE_URLS.has(url.pathname)) {
    event.respondWith(servePrecached(url.pathname, request));
    return;
  }

  if (request.mode === "navigate") {
    event.respondWith(serveNavigation(request));
  }
});

async function servePrecached(pathname, request) {
  const cache = await caches.open(APP_CACHE_NAME);
  return (await cache.match(pathname)) || fetch(request);
}

async function serveNavigation(request) {
  try {
    return await fetch(request);
  } catch {
    const cache = await caches.open(APP_CACHE_NAME);
    return (await cache.match("/")) || Response.error();
  }
}

async function serveProjectCover(request) {
  const cache = await caches.open(COVER_CACHE_NAME);
  const cached = await cache.match(request);
  if (cached) {
    try {
      await cache.delete(request);
      await cache.put(request, cached.clone());
    } catch {
      // A failed recency update must not hide a valid cached cover.
    }
    return cached;
  }

  const response = await fetch(request);
  if (response.ok && response.type !== "opaque") {
    await cache.put(request, response.clone());
    const keys = await cache.keys();
    const overflow = Math.max(0, keys.length - COVER_CACHE_LIMIT);
    await Promise.all(
      keys.slice(0, overflow).map((cacheKey) => cache.delete(cacheKey)),
    );
  }
  return response;
}
`;
}

async function collectPrecacheEntries(outputDirectory) {
  const out = path.resolve(outputDirectory);
  const files = await walkFiles(out);
  const candidates = [];

  for (const filePath of files) {
    const relativePath = toPosixPath(path.relative(out, filePath));
    let url = null;

    if (relativePath.startsWith("covers/") || relativePath.startsWith("og/")) {
      continue;
    }

    if (relativePath === "index.html") {
      url = "/";
    } else if (relativePath.endsWith("/index.html")) {
      url = `/${relativePath.slice(0, -"index.html".length)}`;
    } else if (
      relativePath.startsWith("_next/static/") &&
      PRECACHE_STATIC_EXTENSIONS.has(path.extname(relativePath).toLowerCase())
    ) {
      url = `/${relativePath}`;
    } else if (relativePath.startsWith("icons/")) {
      url = `/${relativePath}`;
    } else if (
      relativePath === "manifest.webmanifest" ||
      relativePath === "icon.svg"
    ) {
      url = `/${relativePath}`;
    }

    if (url) candidates.push({ filePath, url });
  }

  for (const requiredUrl of ["/", "/manifest.webmanifest", "/icon.svg"]) {
    if (!candidates.some(({ url }) => url === requiredUrl)) {
      throw new Error(`Service worker precache is missing ${requiredUrl}`);
    }
  }

  const urls = new Set();
  const entries = [];
  for (const candidate of candidates.sort((left, right) =>
    left.url.localeCompare(right.url),
  )) {
    if (urls.has(candidate.url)) {
      throw new Error(`Duplicate service worker precache URL ${candidate.url}`);
    }
    urls.add(candidate.url);
    const content = await readFile(candidate.filePath);
    entries.push({
      url: candidate.url,
      sha256: createHash("sha256").update(content).digest("hex"),
    });
  }

  return entries;
}

async function loadSongCount(root, projectId) {
  const songsPath = path.join(root, "src", "projects", projectId, "songs.json");
  const songs = JSON.parse(await readFile(songsPath, "utf8"));
  if (!Array.isArray(songs) || songs.length === 0) {
    throw new Error(`${songsPath} must contain a non-empty song array`);
  }
  return songs.length;
}

function assertRuntimeWorkerContracts(source, projectId) {
  assert.doesNotMatch(source, /\bskipWaiting\s*\(/);
  assert.match(source, /self\.clients\.claim\(\)/);
  assert.match(source, /request\.mode === "navigate"/);
  assert.match(source, /cache\.match\("\/"\)/);
  assert.match(source, /keys\.length - COVER_CACHE_LIMIT/);
  assert.match(source, /await cache\.delete\(request\)/);
  assert.match(source, /await cache\.put\(request, cached\.clone\(\)\)/);
  assert.match(source, new RegExp(`/covers/${escapeRegExp(projectId)}/`));
  for (const foreignProjectId of PROJECT_IDS) {
    if (foreignProjectId !== projectId) {
      assert.doesNotMatch(
        source,
        new RegExp(`/covers/${escapeRegExp(foreignProjectId)}/`),
      );
    }
  }
}

function assertDisabledWorkerContracts(source) {
  assert.match(source, /self\.registration\.unregister\(\)/);
  assert.match(source, /caches\.keys\(\)/);
  assert.match(source, /cacheName\.startsWith\(CACHE_PREFIX\)/);
  assert.doesNotMatch(source, /\bskipWaiting\s*\(/);
  assert.doesNotMatch(source, /addEventListener\("fetch"/);
}

async function runSelfTest() {
  const temporaryRoot = await mkdtemp(
    path.join(os.tmpdir(), "mypick-service-worker-"),
  );
  try {
    const out = path.join(temporaryRoot, "out");
    await writeFixtureExport(out);

    const first = await generateServiceWorker({
      outputDirectory: out,
      projectId: "equal-love",
      songCount: 3,
    });
    await verifyGeneratedServiceWorker({
      outputDirectory: out,
      projectId: "equal-love",
      songCount: 3,
    });
    assertRuntimeWorkerContracts(first.source, "equal-love");
    assert.match(first.source, /const COVER_CACHE_LIMIT = 23;/);
    assert.deepEqual(
      first.entries.map(({ url }) => url),
      [
        "/",
        "/_next/static/app.js",
        "/_next/static/style.css",
        "/icon.svg",
        "/icons/install/equal-love-192.png",
        "/manifest.webmanifest",
        "/songs/",
        "/songs/example/",
      ],
    );
    assert.equal(
      first.cacheVersion,
      computeCacheVersion(first.entries),
      "CACHE_VERSION must be reproducible from sorted URL/content hashes",
    );
    assert.equal(
      first.source,
      (
        await generateServiceWorker({
          outputDirectory: out,
          projectId: "equal-love",
          songCount: 3,
        })
      ).source,
      "identical exports must generate identical workers",
    );

    await writeFile(path.join(out, "_next", "static", "app.js"), "changed");
    const changed = await generateServiceWorker({
      outputDirectory: out,
      projectId: "equal-love",
      songCount: 3,
    });
    assert.notEqual(changed.cacheVersion, first.cacheVersion);

    const otherProject = await generateServiceWorker({
      outputDirectory: out,
      projectId: "nearly-equal-joy",
      songCount: 3,
    });
    assert.notEqual(otherProject.source, changed.source);
    assert.match(otherProject.source, /\/covers\/nearly-equal-joy\//);
    assert.doesNotMatch(otherProject.source, /\/covers\/equal-love\//);

    assertDisabledWorkerContracts(renderDisabledServiceWorker());
    console.log(
      "Service worker fixture checks passed: kill switch, content addressing, exact precache, project scope, cover LRU, and lifecycle.",
    );
  } finally {
    await rm(temporaryRoot, { force: true, recursive: true });
  }
}

async function writeFixtureExport(out) {
  const fixtures = new Map([
    ["index.html", "home"],
    [path.join("songs", "index.html"), "songs"],
    [path.join("songs", "example", "index.html"), "song"],
    [path.join("_next", "static", "app.js"), "app"],
    [path.join("_next", "static", "style.css"), "style"],
    [path.join("icons", "install", "equal-love-192.png"), "icon"],
    ["manifest.webmanifest", "{}"],
    ["icon.svg", "<svg/>"],
    [path.join("og", "equal-love", "home.png"), "not precached"],
    [path.join("og", "index.html"), "not a route"],
    [path.join("covers", "equal-love", "cover.jpg"), "not precached"],
    [path.join("covers", "not-equal-me", "foreign-cover.jpg"), "not precached"],
  ]);
  for (const [relativePath, content] of fixtures) {
    const filePath = path.join(out, relativePath);
    await mkdir(path.dirname(filePath), { recursive: true });
    await writeFile(filePath, content);
  }
}

async function walkFiles(directory) {
  const files = [];
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    throw new Error(
      `Unable to read export directory ${directory}: ${error.message}`,
    );
  }
  for (const entry of entries) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walkFiles(fullPath)));
    } else if (entry.isFile()) {
      files.push(fullPath);
    }
  }
  return files;
}

function assertProjectId(projectId) {
  if (!PROJECT_IDS.has(projectId)) {
    throw new Error(`Unknown project id: ${projectId}`);
  }
}

function toPosixPath(value) {
  return value.split(path.sep).join("/");
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

async function runCli() {
  const options = parseCliOptions(process.argv.slice(2));
  if (options.selfTest) {
    await runSelfTest();
    return;
  }

  const outputDirectory = path.resolve(repositoryRoot, options.out ?? "out");
  const outputPath = path.join(outputDirectory, "sw.js");
  if (options.disable) {
    await mkdir(outputDirectory, { recursive: true });
    const disabledSource = renderDisabledServiceWorker();
    if (options.check) {
      const actual = await readFile(outputPath, "utf8");
      if (actual !== disabledSource) {
        throw new Error("sw.js does not match the disabled kill switch");
      }
      assertDisabledWorkerContracts(actual);
      console.log(`Disabled service worker verified at ${outputPath}.`);
      return;
    }
    await writeFile(outputPath, disabledSource, "utf8");
    console.log(`Generated disabled service worker at ${outputPath}.`);
    return;
  }

  const projectId =
    options.project ?? process.env.NEXT_PUBLIC_PROJECT_ID ?? "equal-love";
  assertProjectId(projectId);
  const songCount = await loadSongCount(repositoryRoot, projectId);
  if (options.check) {
    const result = await verifyGeneratedServiceWorker({
      outputDirectory,
      projectId,
      songCount,
    });
    console.log(
      `Service worker verified for ${projectId} (${result.entries.length} precache entries, cache ${result.cacheVersion}).`,
    );
    return;
  }

  const result = await generateServiceWorker({
    outputDirectory,
    projectId,
    songCount,
  });
  console.log(
    `Generated service worker for ${projectId} at ${outputPath} (${result.entries.length} precache entries, cache ${result.cacheVersion}).`,
  );
}

function parseCliOptions(args) {
  const options = { check: false, disable: false, selfTest: false };
  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === "--check") {
      options.check = true;
      continue;
    }
    if (argument === "--disable") {
      options.disable = true;
      continue;
    }
    if (argument === "--self-test") {
      options.selfTest = true;
      continue;
    }
    if (argument === "--out" || argument === "--project") {
      const value = args[index + 1];
      if (!value) throw new Error(`${argument} requires a value`);
      options[argument.slice(2)] = value;
      index += 1;
      continue;
    }
    throw new Error(
      "Usage: node scripts/generate-service-worker.mjs [--project project-id] [--out output-directory] [--check|--disable|--self-test]",
    );
  }
  if (options.selfTest && (options.check || options.disable)) {
    throw new Error("--self-test cannot be combined with --check or --disable");
  }
  return options;
}

const isDirectRun =
  process.argv[1] &&
  path.resolve(process.argv[1]) ===
    path.resolve(fileURLToPath(import.meta.url));

if (isDirectRun) {
  runCli().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
